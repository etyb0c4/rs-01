import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1280, height: 800 } })
p.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
p.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE:', m.text().slice(0, 300)) })
const shot = (n) => p.screenshot({ path: `/tmp/claude-1000/-home-etyb0c4-perso-portfolio/c5771ad4-c78e-4b18-8257-ffb631cb2a1c/scratchpad/s-lab/${n}.png` })
await p.goto('http://localhost:5199/')
await p.waitForTimeout(1200)
await p.evaluate(() => window.__rs.enter())
await p.waitForFunction(() => !window.__rs.S.auto && window.__rs.S.t > 1.5)
await p.evaluate(() => { const r = window.__rs; r.solve(r.GATES[0]) })
await p.waitForFunction(() => !window.__rs.S.auto && window.__rs.S.t > 10.5)
await p.evaluate(() => { window.__rs.S.target = 35 })
await p.waitForFunction(() => window.__rs.S.t > 31.95, null, { timeout: 20000 })
await p.waitForTimeout(2200)
console.log('at gate2:', await p.evaluate(() => ({ t: window.__rs.S.t.toFixed(2), gap: window.__rs.mono.gap().toFixed(2), visible: window.__rs.mono.group.visible })))
await shot('mono-prompt')
// grab anywhere and drag the dark half down-left toward the paper half
await p.mouse.move(640, 300)
await p.mouse.down()
for (let i = 1; i <= 7; i++) { await p.mouse.move(640 - i * 14, 300 + i * 9, { steps: 1 }); await p.waitForTimeout(30) }
await p.waitForTimeout(200)
console.log('mid-drag gap:', await p.evaluate(() => window.__rs.mono.gap().toFixed(2)))
for (let i = 1; i <= 5; i++) { await p.mouse.move(542 - i * 8, 363 + i * 5, { steps: 1 }); await p.waitForTimeout(30); if (await p.evaluate(() => window.__rs.GATES[1].solved)) break }
await p.mouse.up()
await p.waitForTimeout(480)
await shot('mono-whole')
await p.waitForTimeout(260)
console.log('after drag:', await p.evaluate(() => ({ solved: window.__rs.GATES[1].solved, gap: window.__rs.mono.gap().toFixed(2) })))
await shot('mono-fuse')
await p.waitForTimeout(900)
await shot('mono-flash')
await p.waitForFunction(() => window.__rs.S.t > 35.9, null, { timeout: 15000 }).catch(() => console.log('no advance'))
console.log('end t:', await p.evaluate(() => window.__rs.S.t.toFixed(2)))
await b.close()
