import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1280, height: 800 } })
p.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
p.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE:', m.text().slice(0, 300)) })
const shot = (n) => p.screenshot({ path: `/tmp/claude-1000/-home-etyb0c4-perso-portfolio/c5771ad4-c78e-4b18-8257-ffb631cb2a1c/scratchpad/s-lab/${n}.png` })
await p.goto('http://localhost:5199/')
await p.waitForTimeout(1200)
await p.evaluate(() => window.__rs.enter())
await p.waitForFunction(() => !window.__rs.S.auto && window.__rs.S.t > 1.5)
await p.evaluate(() => { const r = window.__rs; r.solve(r.GATES[0]) })
await p.waitForFunction(() => !window.__rs.S.auto && window.__rs.S.t > 10.5)
await p.evaluate(() => { window.__rs.S.target = 35 })
await p.waitForFunction(() => window.__rs.S.t > 31.95, null, { timeout: 20000 })
await p.waitForTimeout(2300)
await shot('rift')
// tap the rift
await p.mouse.click(640, 400)
await p.waitForTimeout(1600)
await shot('dive1')
await p.waitForTimeout(1700)
await shot('dive2')
await p.waitForTimeout(1300)
await shot('dive3')
console.log('mid:', await p.evaluate(() => ({ solved: window.__rs.GATES[1].solved, dive: window.__rs.G.dive.toFixed(2), t: window.__rs.S.t.toFixed(2) })))
await p.waitForFunction(() => window.__rs.S.t > 35.9, null, { timeout: 15000 }).catch(() => console.log('no advance'))
await p.waitForTimeout(800)
await shot('dive-name')
console.log('end:', await p.evaluate(() => ({ t: window.__rs.S.t.toFixed(2), dive: window.__rs.G.dive.toFixed(2) })))
await b.close()
