import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] })
const p = await b.newPage({ viewport: { width: 1280, height: 800 } })
p.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await p.goto('http://localhost:5199/')
await p.waitForTimeout(1800)
// enter and fast-forward to gate 2
await p.evaluate(() => { const r = window.__rs; r.enter() })
await p.waitForTimeout(3200)
await p.evaluate(() => { const r = window.__rs; r.solve(r.GATES[0]) })
await p.waitForTimeout(3000)
await p.evaluate(() => { window.__rs.S.target = 35 })
await p.waitForTimeout(2500)
const st1 = await p.evaluate(() => ({ t: window.__rs.S.t.toFixed(2), slashOn: document.getElementById('slash').classList.contains('on'), circleOn: document.getElementById('gate').classList.contains('on') }))
console.log('at gate2:', JSON.stringify(st1))
await p.screenshot({ path: '/tmp/claude-1000/-home-etyb0c4-perso-portfolio/c5771ad4-c78e-4b18-8257-ffb631cb2a1c/scratchpad/s-lab/slash-prompt.png' })
// fast diagonal swipe
await p.mouse.move(900, 240)
await p.mouse.down()
for (const [x, y] of [[800, 330], [680, 430], [540, 540], [420, 620]]) { await p.mouse.move(x, y, { steps: 2 }); await p.waitForTimeout(25) }
await p.mouse.up()
await p.waitForTimeout(350)
await p.screenshot({ path: '/tmp/claude-1000/-home-etyb0c4-perso-portfolio/c5771ad4-c78e-4b18-8257-ffb631cb2a1c/scratchpad/s-lab/slash-cut.png' })
const st2 = await p.evaluate(() => ({ solved: window.__rs.GATES[1].solved, t: window.__rs.S.t.toFixed(2) }))
console.log('after swipe:', JSON.stringify(st2))
await p.waitForTimeout(5200)
const st3 = await p.evaluate(() => ({ t: window.__rs.S.t.toFixed(2) }))
console.log('after auto-advance:', JSON.stringify(st3))
await p.screenshot({ path: '/tmp/claude-1000/-home-etyb0c4-perso-portfolio/c5771ad4-c78e-4b18-8257-ffb631cb2a1c/scratchpad/s-lab/slash-after.png' })
await b.close()
